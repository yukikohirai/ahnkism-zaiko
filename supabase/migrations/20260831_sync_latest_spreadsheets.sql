-- 既に同名の商品が追加済みなら再利用する（再実行時の重複防止）。
update inventory_sheet_import source
set product_id = product.id
from public.products product
where source.product_id is null
  and product.is_active = true
  and product.category_id = source.category_id
  and coalesce(product.brand, '') = coalesce(source.brand, '')
  and product.name = source.product_name;

-- 最新シートにしかない商品を共通商品マスタへ追加する。
with missing as (
  select distinct category_id, brand, product_name
  from inventory_sheet_import
  where product_id is null
), inserted as (
  insert into public.products (
    category_id, brand, name, required_qty, sort_order,
    dealer, manufacturer, is_active
  )
  select
    category_id,
    brand,
    product_name,
    0,
    10000 + row_number() over (order by category_id, product_name),
    null,
    case when category_id = 8 then 'ミルボン' else null end,
    true
  from missing
  returning id, category_id, brand, name
)
update inventory_sheet_import source
set product_id = inserted.id
from inserted
where source.product_id is null
  and source.category_id = inserted.category_id
  and coalesce(source.brand, '') = coalesce(inserted.brand, '')
  and source.product_name = inserted.name;

-- 店舗によってカテゴリが食い違わない商品は、シートのカテゴリを採用する。
with source_categories as (
  select product_id, min(category_id) as category_id
  from inventory_sheet_import
  group by product_id
  having count(distinct category_id) = 1
)
update public.products product
set category_id = source.category_id
from source_categories source
where product.id = source.product_id
  and product.category_id is distinct from source.category_id;

-- 現行シートの表記へ修正する。
update public.products
set name = 'シルクアンプル詰替'
where id = 574;

-- シートにない既存商品は削除せず、店舗内の末尾へ移す。
with extras as (
  select
    assigned.store_id,
    assigned.product_id,
    row_number() over (
      partition by assigned.store_id
      order by assigned.sort_order, assigned.product_id
    ) as extra_order
  from public.store_products assigned
  where assigned.is_active = true
    and not exists (
      select 1
      from inventory_sheet_import source
      where source.store_id = assigned.store_id
        and source.product_id = assigned.product_id
    )
)
update public.store_products assigned
set sort_order = 10000 + extras.extra_order,
    updated_at = now()
from extras
where assigned.store_id = extras.store_id
  and assigned.product_id = extras.product_id;

-- 既存のベータ履歴は残しつつ、表示中の現在庫をシート値へ合わせる。
with movement_totals as (
  select store_id, product_id, coalesce(sum(quantity), 0)::integer as quantity
  from public.inventory_movements
  group by store_id, product_id
)
insert into public.store_products (
  store_id, product_id, is_active, required_qty,
  opening_stock, sort_order, dealer_override, updated_at
)
select
  source.store_id,
  source.product_id,
  true,
  source.required_qty,
  source.current_stock - coalesce(movement.quantity, 0),
  source.source_order,
  source.supplier,
  now()
from inventory_sheet_import source
left join movement_totals movement
  on movement.store_id = source.store_id
 and movement.product_id = source.product_id
on conflict (store_id, product_id) do update
set is_active = excluded.is_active,
    required_qty = excluded.required_qty,
    opening_stock = excluded.opening_stock,
    sort_order = excluded.sort_order,
    dealer_override = excluded.dealer_override,
    updated_at = excluded.updated_at;

commit;

select
  store.name,
  count(*) filter (where assigned.is_active) as active_products,
  count(*) filter (where assigned.sort_order < 10000) as sheet_products
from public.store_products assigned
join public.stores store on store.id = assigned.store_id
group by store.id, store.name
order by store.id;



